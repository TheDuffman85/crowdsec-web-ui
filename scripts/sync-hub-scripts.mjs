#!/usr/bin/env node
// Copies the hub shell scripts into server/hub/scripts.generated.ts so the server can
// serve them without reading the repository at run time. A test fails when the two differ.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const escape = (text) => text.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
const entries = [
  ['HUB_EXEC_SCRIPT', 'scripts/hub-exec.sh'],
  ['HUB_UNINSTALL_SCRIPT', 'scripts/hub-uninstall.sh'],
  ['HUB_INSTALL_TEMPLATE', 'scripts/hub-install.sh'],
];
let output = '// Generated by scripts/sync-hub-scripts.mjs from the files in scripts/. Do not edit by hand.\n';
for (const [name, file] of entries) {
  output += `\nexport const ${name} = \`${escape(readFileSync(path.join(root, file), 'utf8'))}\`;\n`;
}
writeFileSync(path.join(root, 'server/hub/scripts.generated.ts'), output);
console.log('server/hub/scripts.generated.ts updated');
